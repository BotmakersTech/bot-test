// Regenerates src/shared/data/indiaLocations.generated.ts — the India
// state -> cities dataset behind <LocationSelects>.
//
// Usage:
//   npm i -D country-state-city
//   node scripts/gen-india-locations.mjs
//   npm uninstall country-state-city   # runtime only needs the generated .ts
//
// Source: country-state-city (dr5hn/countries-states-cities-database), India subset.

import { writeFileSync, statSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const csc = require("country-state-city");

const states = csc.State.getStatesOfCountry("IN").sort((a, b) =>
  a.name.localeCompare(b.name),
);

const out = {};
for (const s of states) {
  const cities = csc.City.getCitiesOfState("IN", s.isoCode)
    .map((c) => c.name.trim())
    .filter(Boolean);
  out[s.name] = Array.from(new Set(cities)).sort((a, b) => a.localeCompare(b));
}

const cityCount = Object.values(out).reduce((n, a) => n + a.length, 0);
const dest = "src/shared/data/indiaLocations.generated.ts";

writeFileSync(
  dest,
  `// AUTO-GENERATED by scripts/gen-india-locations.mjs — do not edit by hand.\n` +
    `// Source: country-state-city (dr5hn countries-states-cities DB), India subset.\n` +
    `// ${Object.keys(out).length} states / UTs, ${cityCount} cities.\n\n` +
    `const INDIA_CITIES_BY_STATE: Record<string, string[]> = ${JSON.stringify(out)};\n\n` +
    `export default INDIA_CITIES_BY_STATE;\n`,
);

console.log(
  `Wrote ${dest} — ${Object.keys(out).length} states, ${cityCount} cities, ${(
    statSync(dest).size / 1024
  ).toFixed(1)} KB`,
);
